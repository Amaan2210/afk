export interface ProfileOptions {
  sessionId: string;
  port: number;
  nodeExe: string;
  cliEntry: string;
}

/**
 * Windows PowerShell 5.1 reads a script without a byte order mark in the ANSI code page, which
 * mangles the `·` below and any non-ASCII path. The caller must write this text as UTF-8.
 */
const BOM = "\uFEFF";

/**
 * A PowerShell double-quoted string. Backtick is the escape character; `$` would expand a
 * variable; PowerShell also ends strings on typographic double quotes.
 */
function psString(s: string): string {
  return `"${s.replace(/[`$"\u201C\u201D\u201E]/g, "`$&")}"`;
}

/**
 * Windows PowerShell 5.1 (and pwsh before 7.3, or with Legacy argument passing) builds a native
 * command line without escaping. An embedded `"` toggles quoting, an empty arg vanishes, and a
 * trailing backslash escapes the quote PowerShell wraps around an arg containing whitespace.
 * PowerShell 5.1 also adds that wrapping only when some whitespace follows an even number of `"`,
 * escaped ones included, so it cannot be relied on. This helper therefore rewrites each string
 * arg for the MSVCRT rules node parses with (node.exe uses the UCRT parser):
 *   - empty: `""`;
 *   - with whitespace: wrapped in `"` here, each `"` as `""` (a literal quote inside a quoted
 *     region), the backslashes before a `"` and at the end doubled. Every `"` inside is then
 *     paired, so PowerShell never adds its own quotes;
 *   - otherwise: each `"` as `\"`, the backslashes before it doubled. PowerShell never quotes
 *     these.
 * PowerShell 7.3 and later passes args intact when `$PSNativeCommandArgumentPassing` is `Standard`
 * or `Windows` (its default), so then they go through unchanged, as non-string args always do.
 * Both the version and the mode are checked: before 7.3 the variable is an ordinary one, which a
 * user may have set without it changing anything.
 */
const FORWARD_ARGS_HELPER = [
  "function afk-forward-args {",
  "  $v = $PSVersionTable.PSVersion",
  "  $mode = Get-Variable PSNativeCommandArgumentPassing -ValueOnly -ErrorAction Ignore",
  "  $intact = ($v.Major -gt 7 -or ($v.Major -eq 7 -and $v.Minor -ge 3)) -and",
  "    ($mode -eq 'Standard' -or $mode -eq 'Windows')",
  "  foreach ($a in $args[0]) {",
  "    if ($intact -or $a -isnot [string]) { ,$a }",
  `    elseif ($a.Length -eq 0) { '""' }`,
  String.raw`    elseif ($a -match '\s') { '"' + (($a -replace '(\\*)"', '$1$1""') -replace '(\\+)\z', '$1$1') + '"' }`,
  String.raw`    else { $a -replace '(\\*)"', '$1$1\"' }`,
  "  }",
  "}",
];

/**
 * The per-session profile each session shell runs at startup. It defines `claude` and `codex`
 * for that shell only, routing them through `afk exec`; the user's own profile and PATH are not
 * touched. Windows PowerShell 5.1 syntax only.
 */
export function renderSessionProfile(o: ProfileOptions): string {
  const exec = `& ${psString(o.nodeExe)} ${psString(o.cliEntry)} exec`;
  const forwarded = "$afkArgs = @(afk-forward-args $args);";
  const lines = [
    "# Generated by AFK for one session. It defines claude and codex for this shell only.",
    `$env:AFK_SESSION_ID = ${psString(o.sessionId)}`,
    `$env:AFK_PORT = ${psString(String(o.port))}`,
    "# Rewrites args so Windows PowerShell 5.1 hands them to node exactly as typed.",
    ...FORWARD_ARGS_HELPER,
    // The user's profile loads first, and in PowerShell an alias outranks a function. -Force also
    // removes ReadOnly aliases.
    "Remove-Item Alias:claude,Alias:codex -Force -ErrorAction SilentlyContinue",
    `function claude { ${forwarded} ${exec} claude @afkArgs }`,
    `function codex { ${forwarded} ${exec} codex @afkArgs }`,
    `try { $Host.UI.RawUI.WindowTitle = ${psString(`afk · ${o.sessionId}`)} } catch {}`,
    `Write-Host ${psString(`afk session ${o.sessionId} · detach: Ctrl+] d`)} -ForegroundColor DarkGray`,
  ];
  return BOM + lines.join("\r\n") + "\r\n";
}
